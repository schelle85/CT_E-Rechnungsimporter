"""Frozen additive AP07 schema. Future changes require a new migration."""
import sqlalchemy as sa

metadata = sa.MetaData()
settings = sa.Table("notification_settings", metadata,
    sa.Column("singleton", sa.SmallInteger, primary_key=True, autoincrement=False),
    sa.Column("version", sa.Integer, nullable=False),
    sa.Column("scope_key", sa.String(64)),
    sa.Column("payload_cipher", sa.Text),
    sa.Column("actor", sa.String(256), nullable=False),
    sa.Column("updated_at", sa.BigInteger, nullable=False),
    sa.CheckConstraint("singleton = 1 AND version >= 0", name="notification_one_settings"))
outbox = sa.Table("notification_outbox", metadata,
    sa.Column("slot_key", sa.String(64), primary_key=True),
    sa.Column("request_fence", sa.String(64), unique=True),
    sa.Column("request_hash", sa.String(64)),
    sa.Column("request_id", sa.String(36)),
    sa.Column("actor", sa.String(64), nullable=False),
    sa.Column("scope_key", sa.String(64), nullable=False),
    sa.Column("kind", sa.String(24), nullable=False),
    sa.Column("period_start", sa.BigInteger, nullable=False),
    sa.Column("period_end", sa.BigInteger, nullable=False),
    sa.Column("due_at", sa.BigInteger, nullable=False),
    sa.Column("stale_at", sa.BigInteger, nullable=False),
    sa.Column("config_version", sa.Integer, nullable=False),
    sa.Column("plan_revision", sa.Integer, nullable=False),
    sa.Column("payload_cipher", sa.Text),
    sa.Column("payload_hash", sa.String(64)),
    sa.Column("monitor_keys", sa.Text, nullable=False, server_default="[]"),
    sa.Column("state", sa.String(24), nullable=False),
    sa.Column("reservations", sa.SmallInteger, nullable=False),
    sa.Column("owner", sa.String(32)),
    sa.Column("lease_until", sa.BigInteger, nullable=False),
    sa.Column("reserved_at", sa.BigInteger, index=True),
    sa.Column("post_started_at", sa.BigInteger),
    sa.Column("completed_at", sa.BigInteger),
    sa.Column("not_before", sa.BigInteger, nullable=False),
    sa.Column("error_code", sa.String(64)),
    sa.Column("http_status", sa.SmallInteger),
    sa.Column("created_at", sa.BigInteger, nullable=False),
    sa.Column("updated_at", sa.BigInteger, nullable=False),
    sa.CheckConstraint("reservations IN (0,1) AND plan_revision >= 0", name="notification_one_reservation"),
    sa.CheckConstraint("reservations = 0 OR reserved_at IS NOT NULL", name="notification_reservation_time"),
    sa.CheckConstraint("state != 'accepted' OR (reservations = 1 AND post_started_at IS NOT NULL AND http_status = 202)", name="notification_acceptance_proof"),
    sa.CheckConstraint("period_start < period_end AND due_at < stale_at", name="notification_period"),
    sa.CheckConstraint("state IN ('prepared','sending','accepted','rejected','unknown','obsolete')", name="notification_state"))
monitor = sa.Table("notification_monitor", metadata,
    sa.Column("monitor_key", sa.String(64), primary_key=True),
    sa.Column("scope_key", sa.String(64), nullable=False),
    sa.Column("kind", sa.String(24), nullable=False),
    sa.Column("payload", sa.Text, nullable=False),
    sa.Column("revision", sa.Integer, nullable=False, server_default="0"),
    sa.Column("updated_at", sa.BigInteger, nullable=False))
